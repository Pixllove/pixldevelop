/**
 * Returns display strings for the given language (defaults to English).
 */
export function getLocalizedProjectFields(project, language) {
  if (!project) {
    return {
      type: '',
      title: '',
      shortDescription: '',
      fullDescription: '',
      highlights: [],
      links: [],
    }
  }
  if (language !== 'de' || !project.de) {
    return {
      type: project.type,
      title: project.title,
      shortDescription: project.shortDescription,
      fullDescription: project.fullDescription,
      highlights: project.highlights,
      links: project.links,
    }
  }
  const d = project.de
  return {
    type: d.type,
    title: d.title,
    shortDescription: d.shortDescription,
    fullDescription: d.fullDescription,
    highlights: d.highlights,
    links: project.links.map((link, i) => ({
      ...link,
      label: d.linkLabels[i] ?? link.label,
    })),
  }
}

export function getProjectById(id) {
  return projects.find((project) => project.id === id) ?? null
}
